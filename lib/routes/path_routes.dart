/// Clase que define las constantes de rutas de la aplicación.
///
/// Esta clase contiene todas las rutas disponibles en la aplicación como
/// constantes estáticas, facilitando su mantenimiento y evitando errores
/// de escritura en las rutas.
class PathRoutes {
  /// Ruta de la pantalla splash (inicio).
  static const splash = '/';

  /// Ruta de autenticación.
  static const auth = '/auth';

  /// Ruta del dashboard principal.
  static const dashboard = '/dashboard';

  /// Ruta de la tarjeta de ítems.
  static const itemsCard = '/item_card';

  /// Ruta del formulario de ítem.
  static const itemForm = '/item_form';

  /// Ruta del detalle de producto.
  static const productDetail = '/product_detail';

  /// Ruta de pagos.
  static const payments = '/payments';
}
